function createTitle({ businessType, assistantType, problemType }) {
  if (businessType === 'ট্রাভেল এজেন্সি' && assistantType === 'কাস্টম জিপিটি') {
    return 'ট্রাভেল প্যাকেজ কাস্টম জিপিটি অনুশীলন';
  }

  if (businessType === 'রেস্টুরেন্ট' && problemType === 'গ্রাহকের সাধারণ প্রশ্ন') {
    return 'রেস্টুরেন্ট গ্রাহক প্রশ্ন সহকারী অনুশীলন';
  }

  if (businessType === 'আইন ফার্ম' && problemType === 'ডকুমেন্ট থেকে উত্তর') {
    return 'আইন ফার্ম ডকুমেন্ট সহকারী অনুশীলন';
  }

  return `${businessType} ${assistantType} ব্রিফ`;
}

function listItems(items) {
  return items.map((item) => `• ${item}`).join('\n');
}

